// NFR-7 / SR-3 canonical wire codec, TypeScript side; mirrors test_NFR07_wire_canonical.py.
// Also consumes simulator-generated vectors (FR-3 vector criterion).
// Expected failure on trunk: NOT_IMPLEMENTED: T-09 (codec); vectors tests also need T-16/T-17.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import {
    WireError,
    decodeCanonical,
    encodeCanonical,
    type CanonicalValue,
    type DecodeLimits,
    type WireErrorCode,
} from "@teecustody/core";
import { describe, expect, it } from "vitest";

const LIMITS: DecodeLimits = { maxBytes: 1024, maxDepth: 8, maxItems: 256 };
const REPO = fileURLToPath(new URL("../../", import.meta.url));
const bytes = (hex: string): Uint8Array => new Uint8Array(Buffer.from(hex, "hex"));
const hex = (b: Uint8Array): string => Buffer.from(b).toString("hex");

const VALID: ReadonlyArray<readonly [string, CanonicalValue, string]> = [
    ["zero", 0, "00"],
    ["uint24", 24, "1818"],
    ["uint64_max", 2n ** 64n - 1n, "1bffffffffffffffff"],
    ["nint64_min", -(2n ** 64n), "3bffffffffffffffff"],
    ["minus_one", -1, "20"],
    ["null", null, "f6"],
    ["true", true, "f5"],
    ["text", "a", "6161"],
    ["bytes", bytes("01"), "4101"],
    ["array", [1, 2], "820102"],
    ["map", new Map([["a", 1]]), "a1616101"],
    [
        "map_sorted",
        new Map([
            ["b", 2],
            ["aa", 1],
        ]),
        "a261620262616101",
    ],
    ["2^53", 2n ** 53n, "1b0020000000000000"],
    ["2^53-1", Number.MAX_SAFE_INTEGER, "1b001fffffffffffff"],
];

const INVALID: ReadonlyArray<readonly [string, string, WireErrorCode | undefined]> = [
    ["non_shortest_uint", "1800", "NONCANONICAL"],
    ["non_shortest_uint16", "1900ff", "NONCANONICAL"],
    ["float16", "f90000", "UNSUPPORTED_TYPE"],
    ["float64", "fb3ff0000000000000", "UNSUPPORTED_TYPE"],
    ["truncated_head", "18", "MALFORMED"],
    ["truncated_text", "6261", "MALFORMED"],
    ["trailing_bytes", "0000", undefined],
    ["indefinite_array", "9f01ff", undefined],
    ["indefinite_text", "7f6161ff", undefined],
    ["map_keys_unsorted", "a2616202616101", "NONCANONICAL"],
    ["map_duplicate_keys", "a2616101616102", undefined],
    ["empty_input", "", undefined],
];

function wireError(fn: () => unknown): WireError {
    try {
        fn();
    } catch (error) {
        expect(error).toBeInstanceOf(WireError);
        return error as WireError;
    }
    throw new Error("expected WireError");
}

describe("NFR-7 given values with hand-derived canonical encodings", () => {
    it.each(VALID)("%s encodes and decodes exactly", (_n, value, expected) => {
        expect(hex(encodeCanonical(value))).toBe(expected);
        const decoded = decodeCanonical(bytes(expected), LIMITS);
        expect(hex(encodeCanonical(decoded))).toBe(expected);
    });

    it("decodes integers as number when safe and bigint otherwise", () => {
        expect(decodeCanonical(bytes("1b001fffffffffffff"), LIMITS)).toBe(Number.MAX_SAFE_INTEGER);
        expect(decodeCanonical(bytes("1b0020000000000000"), LIMITS)).toBe(2n ** 53n);
        expect(decodeCanonical(bytes("1bffffffffffffffff"), LIMITS)).toBe(2n ** 64n - 1n);
    });

    it("refuses integers outside 64-bit CBOR range", () => {
        expect(hex(encodeCanonical(2n ** 64n - 1n))).toBe("1bffffffffffffffff");
        expect(() => encodeCanonical(2n ** 64n)).toThrow();
        expect(() => encodeCanonical(-(2n ** 64n) - 1n)).toThrow();
    });

    it("keeps the proto-polluting key __proto__ as ordinary data", () => {
        const decoded = decodeCanonical(bytes("a1695f5f70726f746f5f01"), LIMITS) as ReadonlyMap<
            string,
            CanonicalValue
        >;
        expect(decoded.get("__proto__")).toBe(1);
        expect(({} as Record<string, unknown>).polluted).toBeUndefined();
    });
});

describe("NFR-7 given non-canonical, unsupported or malformed input", () => {
    it.each(INVALID)("%s is rejected", (_n, input, code) => {
        const err = wireError(() => decodeCanonical(bytes(input), LIMITS));
        expect(err.message).toBe(err.code);
        if (code !== undefined) expect(err.code).toBe(code);
    });

    it("enforces size, depth and item limits", () => {
        expect(wireError(() => decodeCanonical(new Uint8Array(2000), LIMITS)).code).toBe(
            "TOO_LARGE",
        );
        expect(wireError(() => decodeCanonical(bytes("81".repeat(20) + "00"), LIMITS)).code).toBe(
            "LIMIT_EXCEEDED",
        );
        expect(() =>
            decodeCanonical(bytes(`98ff${"00".repeat(255)}`), { ...LIMITS, maxItems: 100 }),
        ).toThrow(WireError);
    });
});

describe("NFR-7 / FR-3 given vectors generated by the simulator CLI", () => {
    it("decodes the suite canonically and agrees with the Python differential corpus", () => {
        const out = mkdtempSync(join(tmpdir(), "tcv"));
        try {
            execFileSync("uv", ["run", "python", "-m", "teecustody_sim", "vectors", "--out", out], {
                cwd: REPO,
                stdio: "pipe",
                timeout: 120_000,
            });
            const suite = new Uint8Array(readFileSync(join(out, "attestation", "suite.cbor")));
            const decoded = decodeCanonical(suite, {
                maxBytes: 1 << 20,
                maxDepth: 16,
                maxItems: 100_000,
            });
            expect(hex(encodeCanonical(decoded))).toBe(hex(suite));

            const corpus = JSON.parse(
                readFileSync(join(out, "wire", "differential-corpus.json"), "utf8"),
            ) as {
                limits: { max_bytes: number; max_depth: number; max_items: number };
                cases: { id: string; hex: string; outcome: string }[];
            };
            expect(corpus.cases.length).toBeGreaterThanOrEqual(500);
            const limits: DecodeLimits = {
                maxBytes: corpus.limits.max_bytes,
                maxDepth: corpus.limits.max_depth,
                maxItems: corpus.limits.max_items,
            };
            for (const c of corpus.cases) {
                if (c.outcome === "accept") {
                    const value = decodeCanonical(bytes(c.hex), limits);
                    expect(hex(encodeCanonical(value)), c.id).toBe(c.hex);
                } else {
                    expect(wireError(() => decodeCanonical(bytes(c.hex), limits)).code, c.id).toBe(
                        c.outcome,
                    );
                }
            }
        } finally {
            rmSync(out, { recursive: true, force: true });
        }
    }, 150_000);
});
